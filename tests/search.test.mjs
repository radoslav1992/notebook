import assert from 'node:assert/strict';

const { ftsQuery, rrf, stem } = await import('../src/lib/search.ts');

let pass = 0;
const t = (name, fn) => { fn(); pass++; console.log('  ok  ' + name); };

console.log('търсене по думи');

t('думите стават представки, защото българският мени отзад', () => {
  // Проверено срещу истински FTS5: MATCH 'закон' не намира „Закона“, „Законът“
  // и „законите“, а MATCH 'закон*' ги намира всичките.
  assert.equal(ftsQuery('закон'), 'закон*');
  assert.equal(ftsQuery('университет'), 'университет*');
});

t('окончанието пада, за да работи и обратната посока', () => {
  // Проверено срещу истински FTS5 върху текст с „стипендия“: „стипендиите*“
  // връща нула, „стипенди*“ намира пасажа. Затова се реже, преди да се сложи *.
  assert.equal(stem('стипендиите'), 'стипенди');
  assert.equal(stem('законите'), 'закон');
  assert.equal(stem('закона'), 'закон');
  assert.equal(stem('университетите'), 'университет');
  // „пише“ остава цяло: коренът „пиш“ е под четири знака. Глаголите са по-зле
  // покрити от имената, но там перифразата е работа на векторното търсене.
  assert.equal(ftsQuery('какво пише за стипендиите'), 'пише* OR стипенди*');
});

t('късите корени не се режат до неузнаваемост', () => {
  // „три“ → „тр*“ би хванало всичко от „трябва“ до „трети“.
  assert.equal(stem('три'), 'три');
  assert.equal(stem('цели'), 'цели');
  // Под 4 знака остатък изобщо не се пипа.
  for (const w of ['коте', 'село', 'ръка']) assert.equal(stem(w), w);
});

t('служебните думи отпадат', () => {
  // Иначе „на*“ и „се*“ хващат половината текст и изместват същинското.
  assert.equal(ftsQuery('и на от за с'), null);
});

t('числата се търсят точно, не като представка', () => {
  // „21*“ би хванало 21, 210, 2100 — точно обратното на смисъла на „чл. 21“.
  assert.equal(ftsQuery('чл. 21'), 'чл OR 21');
  assert.equal(ftsQuery('Регламент 2016/679'), 'регламент* OR 2016 OR 679');
});

t('късите думи също се търсят точно', () => {
  // „чл“ трябва да работи, но „чл*“ лови „член“, „члена“, „членство“…
  assert.equal(ftsQuery('чл'), 'чл');
});

t('всичко освен букви и цифри пада — иначе въпросът става 500', () => {
  // Всеки от тези низове гърми, ако влезе суров в MATCH. Проверено срещу
  // истински FTS5: тирето дава „no such column: 21“, самотната звездичка —
  // „unknown special query“, кавичката — синтактична грешка.
  assert.equal(ftsQuery('чл-21'), 'чл OR 21');
  assert.equal(ftsQuery('"закон"'), 'закон*');
  assert.equal(ftsQuery('COVID-19'), 'covid* OR 19');
  assert.equal(ftsQuery('***'), null);
  assert.equal(ftsQuery(''), null);
  assert.equal(ftsQuery('?!.,;'), null);

  // Резервираните думи на FTS5 не бива да излизат голи.
  for (const q of ['NEAR', 'AND', 'OR', 'NOT']) {
    const out = ftsQuery(q);
    assert.ok(out === null || /\*$/.test(out), `${q} → ${out}`);
  }
});

t('дългите въпроси се режат, за да не стане изразът безкраен', () => {
  const many = Array.from({ length: 40 }, (_, i) => `дума${i}`).join(' ');
  assert.equal(ftsQuery(many).split(' OR ').length, 12);
});

t('пасаж, намерен от двете търсения, бие намерен само от едното', () => {
  // Същината на сливането: „и двете го сочат“ тежи повече от „едното го сочи
  // първо“. Тук общият е чак трети в двата списъка и пак излиза начело.
  const out = rrf([
    ['a', 'b', 'общ'],
    ['c', 'd', 'общ'],
  ]);
  assert.equal(out[0].id, 'общ');
});

t('еднакво класиран в двата списъка запазва реда на единия', () => {
  // Внимание при четене на числата: сборът 1/61 + 1/63 е по-голям от 2/62,
  // тоест „първи и трети“ бие „втори и втори“ — 1/x е изпъкнала. Затова
  // симетричен обратен ред не размества нищо и това е нормално, не грешка.
  const out = rrf([
    ['a', 'b', 'c'],
    ['a', 'b', 'c'],
  ]);
  assert.deepEqual(out.map((o) => o.id), ['a', 'b', 'c']);
});

t('единичен списък запазва реда си', () => {
  // Когато търсенето по думи няма мнение, редът на Vectorize трябва да оцелее.
  const out = rrf([['x', 'y', 'z']]);
  assert.deepEqual(out.map((o) => o.id), ['x', 'y', 'z']);
});

t('пасаж само в едното класиране пак влиза', () => {
  // Точно това е смисълът: „чл. 21“ го намира само търсенето по думи.
  const out = rrf([['a'], ['b']]);
  assert.deepEqual(out.map((o) => o.id).sort(), ['a', 'b']);
});

console.log('\n' + pass + ' checks passed');

/**
 * Търсене по думи и сливане с търсенето по смисъл.
 *
 * Векторното търсене е силно там, където въпросът е перифразиран, и слабо
 * точно там, където студентът е най-точен: „чл. 21“, „Регламент 2016/679“,
 * собствени имена, съкращения. Тези низове нямат близък смисъл на нищо — имат
 * само себе си. Затова към тях върви и обикновено търсене по думи (FTS5 в D1),
 * а двата списъка се сливат.
 */

/**
 * Български думи, които се срещат навсякъде и само разреждат резултата.
 * Списъкът е нарочно къс: махаме служебните думи, не съдържанието.
 */
const STOPWORDS = new Set([
  'а', 'ако', 'ами', 'без', 'бъде', 'беше', 'би', 'бил', 'било', 'близо', 'в', 'ви', 'вие',
  'все', 'всеки', 'всичко', 'където', 'като', 'какво', 'как', 'кога', 'кой', 'която', 'което',
  'които', 'който', 'да', 'дали', 'до', 'е', 'един', 'една', 'едно', 'ето', 'за', 'защо',
  'и', 'из', 'или', 'им', 'има', 'имат', 'иска', 'й', 'каза', 'ли', 'ме', 'между', 'ми',
  'мога', 'му', 'на', 'над', 'най', 'не', 'него', 'нея', 'ни', 'ние', 'но', 'някои', 'няма',
  'обаче', 'около', 'освен', 'от', 'още', 'по', 'повече', 'под', 'при', 'през', 'първо',
  'с', 'са', 'само', 'се', 'си', 'след', 'сме', 'според', 'сте', 'съм', 'със', 'също',
  'т', 'тази', 'така', 'такива', 'такъв', 'там', 'твой', 'те', 'тези', 'ти', 'този', 'то',
  'това', 'този', 'той', 'толкова', 'точно', 'три', 'тук', 'тъй', 'тя', 'тях', 'у', 'ще',
  'щом', 'я',
  // Английски служебни думи се срещат в чужди източници.
  'a', 'an', 'and', 'are', 'as', 'at', 'be', 'but', 'by', 'for', 'from', 'in', 'is', 'it',
  'of', 'on', 'or', 'that', 'the', 'this', 'to', 'was', 'were', 'with',
]);

/**
 * Български окончания, подредени от дълго към късо.
 *
 * Не е речник и не е пълен морфологичен анализ — само членуването и най-честите
 * окончания за число и род, тоест това, което един и същ корен носи в различни
 * изречения.
 */
const SUFFIXES = [
  'ите', 'ъте', 'ята', 'ето', 'ата', 'ият',
  'ове', 'еве', 'ища', 'ета', 'ия', 'ът', 'ят', 'та', 'то', 'те',
  'и', 'а', 'о', 'е', 'я', 'ъ',
];
// Нарочно ги няма „ните“, „ията“, „ищата“: те изяждат съгласна от самия корен
// („законите“ → „зако“), а къс корен като представка лови несвързани думи —
// „зако*“ хваща и „закачка“, и „закопчалка“. По-добре пропуснато съвпадение,
// отколкото шумно: другото търсене пак може да го намери.

/**
 * Реже окончанието на думата от въпроса, за да остане коренът.
 *
 * Представката сама по себе си работи само в едната посока: „закон*“ намира
 * „законите“, но „законите*“ не намира „закон“. А човек пише както му дойде —
 * „какво пише за стипендиите“, когато в текста стои „стипендия“. Проверено
 * срещу истински FTS5: „стипендиите*“ връща нула, „стипенди*“ намира пасажа.
 *
 * Реже се само докато остават поне 4 знака: под това корените се сливат
 * („три“ → „тр*“) и представката започва да лови несвързани думи.
 */
export function stem(word: string): string {
  for (const suffix of SUFFIXES) {
    if (word.length - suffix.length >= 4 && word.endsWith(suffix)) {
      return word.slice(0, -suffix.length);
    }
  }
  return word;
}

/**
 * Превръща въпроса в MATCH израз за FTS5.
 *
 * Две неща, които не са украса:
 *
 * 1. **Чисти се до букви и цифри.** Изразът след MATCH е синтаксис, не текст:
 *    въпрос с тире („чл-21“) гърми с „no such column: 21“, кавичка гърми със
 *    синтактична грешка, а самотна звездичка — с „unknown special query“.
 *    Тоест без чистене всеки по-особен въпрос става 500.
 *
 * 2. **Всяка дума се реже до корен и става представка (`закон*`).** Българският
 *    мени думите отзад — „закон“, „закона“, „законът“, „закони“, „законите“ — и
 *    точното търсене на „закон“ не намира нито една от тях. Проверено:
 *    `MATCH 'закон'` връща нула, `MATCH 'закон*'` ги връща всичките. Рязането е
 *    заради обратната посока: човек пише „стипендиите“, а в текста стои
 *    „стипендия“, и „стипендиите*“ пак не намира нищо (виж `stem`).
 *
 * Връща `null`, когато не е останало нищо смислено — тогава търсенето по думи
 * просто се пропуска, вместо да пита с празен израз (той също е грешка).
 */
export function ftsQuery(question: string): string | null {
  const terms: string[] = [];

  for (const raw of question.toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (!raw) continue;
    if (STOPWORDS.has(raw)) continue;
    if (terms.length >= 12) break;

    // Числата се търсят точно: „21“ не бива да хване „2100“, а и представка от
    // цифри съвпада с прекалено много.
    if (/^\p{N}+$/u.test(raw)) {
      terms.push(raw);
      continue;
    }
    // Под три знака представката лови половината текст („с*“), затова къси
    // думи се търсят точно — така „чл“ пак работи.
    terms.push(raw.length >= 3 ? `${stem(raw)}*` : raw);
  }

  if (terms.length === 0) return null;
  // OR, а не AND: достатъчно е да съвпадне част от въпроса, а подредбата се
  // грижи по-пълните съвпадения да излязат горе.
  return terms.join(' OR ');
}

/**
 * Reciprocal Rank Fusion — слива класирания, без да сравнява оценките им.
 *
 * Косинусовата близост (0..1) и BM25 (отрицателна, без горна граница) не са в
 * една мярка и не се събират смислено. При малка тетрадка BM25 дори излиза
 * точно 0, защото IDF на дума, срещана в половината пасажи, е log(1) — тоест
 * оценките са и нестабилни. Затова се ползва само редът: пасаж, който и двете
 * търсения слагат високо, изпреварва пасаж, който само едното обожава.
 */
export function rrf(rankings: string[][], k = 60): { id: string; score: number }[] {
  const scores = new Map<string, number>();

  for (const list of rankings) {
    list.forEach((id, i) => {
      scores.set(id, (scores.get(id) ?? 0) + 1 / (k + i + 1));
    });
  }

  return [...scores.entries()]
    .map(([id, score]) => ({ id, score }))
    .sort((a, b) => b.score - a.score);
}

/**
 * Една грешка за всички доставчици на модели. Google и Cloudflare отговарят с
 * различни тела, но приложението нагоре по веригата се интересува само от три
 * неща: какъв е статусът, какво да покаже на човека, и дали проблемът е в ключа.
 */
export class AiError extends Error {
  constructor(
    readonly status: number,
    message: string,
    readonly detail?: unknown,
    /**
     * Проблем с достъпа, а не със самата заявка. Google връща част от тези с
     * 400, затова статусът не е достатъчен, за да се разпознаят.
     */
    readonly keyProblem = false,
  ) {
    super(message);
    this.name = 'AiError';
  }
}

/**
 * Колко чакаме един отговор от модел, преди да се откажем.
 *
 * Аудио прегледът е най-дългият случай: един сегмент от ~1400 знака се озвучава
 * за десетина секунди, тоест 90 е с голям запас и хваща само истинско увисване.
 */
export const MODEL_TIMEOUT_MS = 90_000;

/**
 * Отказва се от чакане, вместо да блокира.
 *
 * Без това увиснала заявка към модел държи цялото изпълнение, докато worker-ът не
 * бъде убит — а задачата остава на 55% и никой не разбира защо. Засичането на
 * заклещени задачи после я маркира като провалена, но чак след три минути и без
 * да каже какво е чакало.
 *
 * Промисът НЕ се прекъсва — `Promise.race` не спира заявката, само спира да я
 * чака. Затова оригиналът получава тих `catch`: иначе късен отказ излиза като
 * необработено отхвърляне.
 */
export function withTimeout<T>(
  work: Promise<T>,
  what: string,
  ms = MODEL_TIMEOUT_MS,
): Promise<T> {
  work.catch(() => {});
  let timer: ReturnType<typeof setTimeout> | undefined;
  return Promise.race([
    work.finally(() => clearTimeout(timer)),
    new Promise<never>((_, reject) => {
      timer = setTimeout(
        () =>
          reject(
            new AiError(
              504,
              `${what} не отговори за ${Math.round(ms / 1000)} секунди. Опитай пак — ако се повтаря, моделът или мрежата към него не са в ред.`,
            ),
          ),
        ms,
      );
    }),
  ]);
}

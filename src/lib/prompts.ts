export function podcastScriptPrompt(language: string, minutes: number): string {
  const lang = LANGUAGE_NAMES[language] ?? 'български';
  return `Напиши сценарий за разговорен подкаст на ${lang} по подадените източници.

Двама водещи: ${HOSTS.a.name} (води разговора, задава въпросите) и ${HOSTS.b.name} (обяснява, дава примери).

Изисквания:
- Около ${minutes} минути говорене — това са приблизително ${minutes * 150} думи.
- Започва без формално представяне: направо в темата, с въпрос или наблюдение, което хваща.
- Само неща от източниците. Никакви външни факти, статистики или имена.
- Числата се изговарят с думи там, където това звучи по-естествено.
- Разговорен български: кратки изречения, прекъсвания, „чакай“, „добре, но“, истинско несъгласие когато източниците си противоречат.
- Без изброявания на глас. Без „в тази точка ще разгледаме“. Това е разговор, не презентация.
- Накрая: какво остава отворено според самите източници.

Формат — по един ред на реплика, точно така:
${HOSTS.a.name}: текст на репликата
${HOSTS.b.name}: текст на репликата

Никакви режисьорски указания, звукови ефекти или заглавия. Само реплики.`;
}


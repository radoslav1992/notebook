export type StudioTaskKey = keyof typeof STUDIO_TASKS;

/**
 * Кои четири материала се показват за дадена употреба.
 *
 * Три са общи за всички — резюме, хронология, отчет — а четвъртият е този, който
 * различава: изпит, задължения, обзор, стъпки. Първият също се мени: „Учебно
 * ръководство“ е нужното при учене и е чуждо навсякъде другаде.
 */
export function tilesFor(useCase: UseCase): StudioTaskKey[] {
  switch (useCase) {
    case 'study':
      return ['study_guide', 'timeline', 'exam', 'briefing'];
    case 'legal':
      return ['summary', 'timeline', 'obligations', 'briefing'];
    case 'research':
      return ['summary', 'timeline', 'review', 'briefing'];
    case 'work':
      return ['summary', 'timeline', 'actions', 'briefing'];
    default:
      return ['summary', 'timeline', 'questions', 'briefing'];
  }
}

